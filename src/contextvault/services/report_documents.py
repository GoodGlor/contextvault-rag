"""Execute a ``documents`` report section: RAG retrieve → grounded answer.

Reuses the query path's machinery wholesale — grant-filtered retrieval and the
provider-agnostic ``answer`` contract — but constructs its own embedder and LLM
provider because report generation runs in a background task with no request
context (``deps.get_embedder``/``deps.build_repo_llm`` are request-scoped).

Honesty rules: an empty retrieval or a ``not_in_vault`` refusal
becomes the note below — never a fabricated answer. Retrieval runs under the
*requesting user's* grants, exactly like the chat query path; a requester
without an active grant honestly finds nothing.
"""

import uuid

from sqlalchemy.ext.asyncio import AsyncSession

from contextvault.core.config import get_settings
from contextvault.embeddings.gemini import GeminiEmbeddingProvider
from contextvault.llm import get_llm_provider
from contextvault.llm.base import Citation
from contextvault.models import LLMProviderName, Source
from contextvault.retrieval import retrieve
from contextvault.services import providers as provider_service
from contextvault.services.report_format import label
from contextvault.services.report_planner import PlannedSection
from contextvault.services.report_types import SectionResult, SectionSourceRef

__all__ = [
    "NO_DOCUMENTS_NOTE",
    "EMBEDDINGS_UNAVAILABLE",
    "execute_documents_section",
    "provider_service",
    "retrieve",
    "get_llm_provider",
    "GeminiEmbeddingProvider",
]

# Kept as the English default; localised text comes from ``report_format.label``
# so a Ukrainian report does not end on an English sentence.
NO_DOCUMENTS_NOTE = "No relevant information was found in the documents for this section."
EMBEDDINGS_UNAVAILABLE = (
    "Document search is unavailable: configure a verified Gemini API key "
    "(embeddings are generated by Gemini)."
)


async def _resolve_cited_sources(
    session: AsyncSession, citations: list[Citation]
) -> list[SectionSourceRef]:
    """Map each distinct ``[n]`` marker to its source document's title."""
    refs: list[SectionSourceRef] = []
    seen: set[int] = set()
    for citation in citations:
        if citation.number in seen:
            continue
        seen.add(citation.number)
        source = await session.get(Source, citation.source_id)
        title = source.title if source is not None else "?"
        refs.append(
            SectionSourceRef(number=citation.number, title=title, source_id=citation.source_id)
        )
    return refs


async def execute_documents_section(
    session: AsyncSession,
    *,
    repository_id: uuid.UUID,
    requested_by: uuid.UUID | None,
    planned: PlannedSection,
    provider_name: str,
    api_key: str,
    model: str,
    base_url: str | None,
    language: str = "en",
) -> SectionResult:
    """Answer one planned section from the repository's ingested sources."""

    def _note() -> SectionResult:
        return SectionResult(
            title=planned.title,
            source="documents",
            sub_question=planned.sub_question,
            kind="text",
            prose=label("no_documents", language),
            # Marked here, where it is known. Every "found nothing" path returns
            # this note, and downstream cannot tell it from a genuine answer that
            # happened to cite nothing (#185).
            empty=True,
        )

    gemini_key = await provider_service.get_provider_key(session, LLMProviderName.GEMINI)
    if gemini_key is None:
        return SectionResult(
            title=planned.title,
            source="documents",
            sub_question=planned.sub_question,
            kind="error",
            error=EMBEDDINGS_UNAVAILABLE,
        )
    if requested_by is None:
        # No requester means no grants to search under — honestly nothing to read.
        return _note()

    settings = get_settings()
    embedder = GeminiEmbeddingProvider(
        api_key=gemini_key,
        model_name=settings.embedding_model,
        dimension=settings.embedding_dim,
    )
    retrieval = await retrieve(
        session,
        question=planned.sub_question,
        repository_id=repository_id,
        user_id=requested_by,
        embedder=embedder,
    )
    if not retrieval.chunks:
        return _note()

    llm = get_llm_provider(provider_name, api_key=api_key, model=model, base_url=base_url)
    answer = await llm.answer(planned.sub_question, retrieval.chunks)
    if answer.not_in_vault:
        return _note()

    sources = await _resolve_cited_sources(session, answer.citations)
    return SectionResult(
        title=planned.title,
        source="documents",
        sub_question=planned.sub_question,
        kind="text",
        prose=answer.text,
        sources=sources,
    )
